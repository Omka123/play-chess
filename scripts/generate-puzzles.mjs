import { Chess } from "chess.js";
import { writeFile } from "node:fs/promises";
// Original training positions, generated and checked locally rather than copied from a puzzle database.
const puzzles = [];
for (const type of ["r", "q"]) {
  for (const king of [0, 7, 56, 63]) {
    for (let support = 0; support < 64; support++) {
      const distance = (a, b) => Math.max(Math.abs(a % 8 - b % 8), Math.abs(Math.floor(a / 8) - Math.floor(b / 8)));
      if (distance(king, support) !== 2) continue;
      for (let piece = 0; piece < 64; piece++) {
        if ([king, support].includes(piece)) continue;
        const square = (n) => "abcdefgh"[n % 8] + (1 + Math.floor(n / 8));
        const game = new Chess(); game.clear(); game.put({ type: "k", color: "b" }, square(king)); game.put({ type: "k", color: "w" }, square(support)); game.put({ type, color: "w" }, square(piece));
        // The side that just moved cannot already be in check.
        const black = new Chess(game.fen().replace(" w ", " b ")); if (black.isCheck() || game.isGameOver()) continue;
        let mates = 0; for (const move of game.moves()) { game.move(move); if (game.isCheckmate()) mates++; game.undo(); }
        if (mates === 1) { puzzles.push({ title: `${type === "r" ? "Rook" : "Queen"} endgame ${puzzles.filter((p) => p.piece === type).length + 1}`, fen: game.fen(), difficulty: "Beginner", rating: 400, theme: "Endgame mate", piece: type }); break; }
      }
    }
  }
}
await writeFile(new URL("../lib/puzzleBank.js", import.meta.url), `// Generated by scripts/generate-puzzles.mjs; each position has exactly one mating move.\nexport const PUZZLE_BANK = ${JSON.stringify(puzzles, null, 2)};\n`);
console.log(`Generated ${puzzles.length} validated endgame puzzles.`);
