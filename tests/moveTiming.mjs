import assert from "node:assert/strict";
import { elapsedMoveTime, formatMoveTime, validMoveTime } from "../lib/moveTiming.js";
import { createRoom, accessRoom } from "../lib/rooms.js";
import { updateRoom } from "../lib/roomStore.js";
assert.equal(elapsedMoveTime(1000, 3450), 2450);
assert.equal(elapsedMoveTime(null, 3450), null);
assert.equal(elapsedMoveTime(5000, 3450), null);
assert.equal(validMoveTime(-1), false);
assert.equal(formatMoveTime(undefined), "—");
assert.equal(formatMoveTime(0), "0.0s");
assert.equal(formatMoveTime(2450), "2.5s");
assert.equal(formatMoveTime(65000), "1:05");
assert.equal(formatMoveTime(3661000), "1:01:01");
const room = await createRoom({ color: "w", tc: 300, increment: 5 });
const guest = await accessRoom(room.id, room.invite, { type: "join" });
await updateRoom(room.id, (state) => { state.turnStartedAt = Date.now() - 3000; });
await accessRoom(room.id, room.token, { type: "offerDraw" });
const first = await accessRoom(room.id, room.token, { type: "move", from: "e2", to: "e4", ply: 0, timeSpentMs: 999999 });
assert.ok(first.moves[0].timeSpentMs >= 3000 && first.moves[0].timeSpentMs < 10000, "Server timing includes the full turn and ignores a forged client value.");
const read = await accessRoom(room.id, guest.token);
assert.equal(read.moves[0].timeSpentMs, first.moves[0].timeSpentMs);
await updateRoom(room.id, (state) => { state.turnStartedAt = Date.now() - 1500; });
const second = await accessRoom(room.id, guest.token, { type: "move", from: "e7", to: "e5", ply: 1 });
assert.ok(second.moves[1].timeSpentMs >= 1500 && second.moves[1].timeSpentMs < 10000);
console.log("Passed: move duration formatting, missing/invalid timing, full-turn timing across draw offers, independent turns and server authority.");
