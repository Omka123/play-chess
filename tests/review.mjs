import assert from "node:assert/strict";
import { Chess } from "chess.js";
import { reviewPosition } from "../lib/review.js";
import { arrowGeometry, reviewArrows } from "../lib/reviewArrows.js";

const opening = new Chess();
opening.move("f3"); opening.move("e5");
const before = opening.fen();
const missedDefense = reviewPosition(before, { from: "g2", to: "g4" });
assert.equal(missedDefense.label, "Blunder");
assert.match(missedDefense.reason, /immediate checkmate/);
assert.notEqual(missedDefense.best, "g4");
const arrows = reviewArrows(missedDefense, before);
assert.equal(arrows.length, 2);
assert.deepEqual([arrows[0].from, arrows[0].to], ["g2", "g4"]);
const suggestion = new Chess(before).move(missedDefense.bestMove);
assert.equal(suggestion.san, missedDefense.best);
assert.deepEqual(reviewArrows(missedDefense, new Chess().fen()), []);
assert.deepEqual(reviewArrows(null, before), []);
const whiteArrow = arrowGeometry({ from: "e2", to: "e4" }, "w");
const blackArrow = arrowGeometry({ from: "e2", to: "e4" }, "b");
assert.deepEqual(whiteArrow.end, { x: 450, y: 450 });
assert.deepEqual(blackArrow.end, { x: 350, y: 350 });
assert.equal(whiteArrow.angle, -90);
assert.equal(blackArrow.angle, 90);
const knightArrow = arrowGeometry({ from: "g1", to: "f3" }, "w");
assert.match(knightArrow.path, /^M 650 750 L 650 550 L/);
opening.move("g4");
const mate = reviewPosition(opening.fen(), { from: "d8", to: "h4" });
assert.equal(mate.played, "Qh4#");
assert.equal(mate.loss, 0);
assert.equal(mate.label, "Good");
const hangingQueen = reviewPosition("3r3k/8/8/8/8/8/8/K2Q4 w - - 0 1", { from: "d1", to: "d4" });
assert.equal(hangingQueen.label, "Blunder");
assert.ok(hangingQueen.loss >= 800);
assert.throws(() => reviewPosition(before, { from: "a1", to: "a8" }), /illegal/);
console.log("Passed: immediate mate allowed, mating move, hanging queen, and invalid review move.");
