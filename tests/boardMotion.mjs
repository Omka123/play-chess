import assert from "node:assert/strict";
import { Chess } from "chess.js";
import { boardPoint, moveAnimations } from "../lib/boardMotion.js";
const position = (game) => Object.fromEntries(game.board().flat().filter(Boolean).map((piece) => [piece.square, piece]));
assert.deepEqual(boardPoint("a8", "w"), { x: 0, y: 0 });
assert.deepEqual(boardPoint("a8", "b"), { x: 7, y: 7 });
const opening = new Chess();
const before = position(opening);
const move = opening.move("e4");
assert.equal(moveAnimations(before, position(opening), move)[0].to, "e4");
assert.deepEqual(moveAnimations(position(opening), before, move), []);
const castle = new Chess("r3k2r/8/8/8/8/8/8/R3K2R w KQkq - 0 1");
const castleBefore = position(castle);
const castleMove = castle.move("O-O");
assert.deepEqual(moveAnimations(castleBefore, position(castle), castleMove).map((m) => [m.from, m.to]), [["e1", "g1"], ["h1", "f1"]]);
const promotion = new Chess("7k/P7/8/8/8/8/8/K7 w - - 0 1");
const promotionBefore = position(promotion);
const promotionMove = promotion.move({ from: "a7", to: "a8", promotion: "q" });
assert.equal(moveAnimations(promotionBefore, position(promotion), promotionMove)[0].type, "q");
console.log("Passed: move animation coordinates, board orientation, reset handling, castling and promotion.");
