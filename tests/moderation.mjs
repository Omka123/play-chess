import assert from "node:assert/strict";
import { randomUUID } from "node:crypto";
import { unlink } from "node:fs/promises";
import path from "node:path";
import { registerPlayer, socialAction, matchmaking } from "../lib/community.js";
import { communityTransaction } from "../lib/communityStore.js";
import { isModerator, moderationOverview, moderationAction, submitReport } from "../lib/moderation.js";
import { createRoom, accessRoom } from "../lib/rooms.js";
import { saveGame, shareGame, sharedGame } from "../lib/gameHistory.js";

const prefix = randomUUID().slice(0, 8);
const admin = { id: `moderator-${prefix}`, name: "Moderator", email: "moderator@example.test" };
const reporter = { id: `reporter-${prefix}`, name: "Reporter", email: "reporter@example.test" };
const target = { id: `target-${prefix}`, name: "Target" };
const outsider = { id: `outsider-${prefix}`, name: "Outsider" };
const original = process.env.MODERATOR_EMAILS;
const gameId = `test-${randomUUID()}`;
let room, replay;
process.env.MODERATOR_EMAILS = " moderator@example.test ";
try {
  await Promise.all([admin, reporter, target, outsider].map(registerPlayer));
  const targetProfile = await registerPlayer(target);
  assert.equal(isModerator(admin), true);
  assert.equal(isModerator({ ...reporter, staff: true }), false);
  await assert.rejects(moderationOverview(reporter), /Moderator access/);
  await assert.rejects(moderationAction(reporter, { type: "suspend", userId: target.id, note: "Forged role claim" }), /Moderator access/);
  const report = await submitReport(reporter, { type: "player", target: targetProfile.username, reason: "inappropriate-name", details: "Please inspect this player's public profile name." });
  assert.equal((await submitReport(reporter, { type: "player", target: targetProfile.username, reason: "other", details: "A duplicate report should not create a new record." })).id, report.id);
  assert.equal((await moderationOverview(admin)).reports.find((entry) => entry.id === report.id).status, "open");
  await assert.rejects(moderationAction(admin, { type: "suspend", userId: target.id, note: "" }), /note/);
  await assert.rejects(moderationAction(admin, { type: "suspend", userId: admin.id, note: "Cannot suspend staff" }), /Moderator accounts/);
  await assert.rejects(moderationAction(admin, { type: "resetProfile", userId: "__proto__", note: "Reject prototype key" }), /not found/);
  room = await createRoom({ color: "w", tc: 300 }, reporter);
  await accessRoom(room.id, room.invite, { type: "join" }, target);
  await assert.rejects(submitReport(outsider, { type: "game", target: room.id, reason: "cheating", details: "This user must not report a private game they never joined." }), /participated/);
  const gameReport = await submitReport(reporter, { type: "game", target: room.id, reason: "cheating", details: "Please review the moves from the game I participated in." });
  const evidence = (await moderationOverview(admin)).reports.find((entry) => entry.id === gameReport.id).evidence;
  assert.equal(evidence.tokens, undefined); assert.equal(evidence.invite, undefined); assert.equal(evidence.opponentId, target.id);
  await matchmaking(target, { tc: 60 });
  await moderationAction(admin, { type: "suspend", userId: target.id, note: "Test: inappropriate profile under review" });
  assert.equal(await communityTransaction((state) => Boolean(state.queue[target.id]), { readOnly: true }), false);
  await assert.rejects(createRoom({}, target), /suspended/);
  await assert.rejects(matchmaking(target, { tc: 60 }), /suspended/);
  await assert.rejects(socialAction(target, { type: "profile", username: "another_name", name: "Another", avatar: "king" }), /suspended/);
  assert.equal((await socialAction(target)).profile.suspended, true);
  await moderationAction(admin, { type: "restore", userId: target.id, note: "Test: review completed, restore access" });
  await moderationAction(admin, { type: "resetProfile", userId: target.id, note: "Test: reset inappropriate profile" });
  const reset = await registerPlayer(target); assert.equal(reset.name, "Chess player"); assert.match(reset.username, /^reset_/);
  const renamedRoom = await createRoom({}, target); assert.equal(Object.values(renamedRoom.names)[0], "Chess player");
  await unlink(path.join(process.cwd(), ".gambit-rooms", `${renamedRoom.id}.json`));
  await saveGame(reporter.id, { id: gameId, mode: "friend", moves: [], names: { w: "Reporter", b: "Target" }, color: "w", outcome: "draw", result: { title: "Draw", detail: "Draw by agreement." }, finishedAt: Date.now(), opponentId: target.id });
  replay = await shareGame(reporter.id, gameId);
  assert.equal((await sharedGame(replay)).opponentId, undefined);
  await moderationAction(admin, { type: "hideReplay", replayId: replay, note: "Test: hide reported public replay" });
  assert.equal(await sharedGame(replay), null);
  await moderationAction(admin, { type: "restoreReplay", replayId: replay, note: "Test: restore appropriate replay" });
  assert.equal((await sharedGame(replay)).id, replay);
  await moderationAction(admin, { type: "resolve", reportId: report.id, note: "Profile reset and report resolved" });
  const overview = await moderationOverview(admin);
  assert.equal(overview.reports.find((entry) => entry.id === report.id).status, "resolved");
  assert.ok(overview.audit.some((entry) => entry.action === "hideReplay"));
  console.log("Passed: moderator allowlist, denied role forgery, private game reports, deduplication, suspension enforcement, queue removal, profile reset, replay hide/restore and audit trail.");
} finally {
  if (original === undefined) delete process.env.MODERATOR_EMAILS; else process.env.MODERATOR_EMAILS = original;
  if (room) await unlink(path.join(process.cwd(), ".gambit-rooms", `${room.id}.json`)).catch(() => {});
  await unlink(path.join(process.cwd(), ".gambit-history", reporter.id, `${gameId}.json`)).catch(() => {});
  if (replay) await unlink(path.join(process.cwd(), ".gambit-history", "shared", `${replay}.json`)).catch(() => {});
}
